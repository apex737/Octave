% [a; b]     : 원소/행렬을 세로로 이어 붙임
% start:end  : start부터 end까지 1씩 증가하는 벡터 (예: 1:10)
% A(:, col)  : 모든 행의 col열 (':'는 해당 방향의 전체를 뜻함)
% A(row, :)  : row행의 모든 열
% A(:)       : 행렬의 모든 원소를 한 열로 펼침
% A'         : 행과 열을 바꾸는 전치
% A == 값    : 조건을 만족하는 위치를 true(1)로 표시
% size(A,1)  : 행 개수, size(A,2) : 열 개수
% find(cond) : cond가 true인 위치의 인덱스 반환
% ================================================================
clc;clear;close all;

% 1-A: ((12 + 7) * 3) / 4 - 5^2
